# ── Coordinator socket ────────────────────────────────────────────────────────


def _coordinator_call(req: dict) -> dict:
    """Send a JSON request to the coordinator Unix socket and return the response."""
    sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    try:
        sock.connect(_COORDINATOR_SOCK)
        sock.sendall((json.dumps(req) + "\n").encode())
        buf = b""
        while b"\n" not in buf:
            chunk = sock.recv(65536)
            if not chunk:
                break
            buf += chunk
        return json.loads(buf.split(b"\n")[0])
    finally:
        sock.close()


# ── Gallery WebSocket manager ──────────────────────────────────────────────────


class _GalleryManager:
    """Manages broadcast to all connected gallery WebSocket clients."""

    def __init__(self) -> None:
        self._clients: set[WebSocket] = set()
        self._lock = asyncio.Lock()

    async def connect(self, ws: WebSocket) -> None:
        await ws.accept()
        async with self._lock:
            self._clients.add(ws)

    async def disconnect(self, ws: WebSocket) -> None:
        async with self._lock:
            self._clients.discard(ws)

    async def broadcast(self, data: Any) -> None:
        text = json.dumps(data)
        async with self._lock:
            dead: list[WebSocket] = []
            for client in self._clients:
                try:
                    await client.send_text(text)
                except Exception:
                    dead.append(client)
            for d in dead:
                self._clients.discard(d)


_gallery = _GalleryManager()


# ── STOMP listener (runs in a background thread) ───────────────────────────────


class _PipelineListener(stomp.ConnectionListener):
    """STOMP listener for loop.events (image ready) and tactical.decisions (verdict)."""

    def __init__(self, loop: asyncio.AbstractEventLoop) -> None:
        self._loop = loop

    def on_error(self, frame: stomp.utils.Frame) -> None:
        print(f"[ui/stomp] error: {frame.body}", file=sys.stderr)

    def on_message(self, frame: stomp.utils.Frame) -> None:
        try:
            msg = json.loads(frame.body)
        except Exception:
            return

        dest = frame.headers.get("destination", "")

        if "loop.events" in dest:
            # Capture image_path for proxying, then notify gallery of new image.
            image_uuid = msg.get("image_uuid", "")
            image_path = msg.get("image_path", "")
            if image_uuid and image_path:
                _image_paths[image_uuid] = image_path
            asyncio.run_coroutine_threadsafe(
                _gallery.broadcast({
                    "type":           "image_ready",
                    "image_uuid":     image_uuid,
                    "workflow_id":    msg.get("workflow_id", ""),
                    "conversation_id": msg.get("conversation_id", ""),
                    "sequence_number": msg.get("sequence_number", 0),
                }),
                self._loop,
            )

        elif "tactical.decisions" in dest:
            # Decision from the LLM — updates verdict in the gallery.
            asyncio.run_coroutine_threadsafe(
                _gallery.broadcast({
                    "type":           "decision",
                    "image_uuid":     msg.get("image_uuid", ""),
                    "decision":       msg.get("decision", {}).get("decision", ""),
                    "reasoning":      msg.get("decision", {}).get("reasoning", ""),
                    "confidence":     msg.get("decision", {}).get("confidence"),
                    "verdict":        msg.get("verdict", {}).get("verdict", ""),
                    "workflow_id":    msg.get("verdict", {}).get("workflow_id", ""),
                    "conversation_id": msg.get("verdict", {}).get("conversation_id", ""),
                }),
                self._loop,
            )


_stomp_conn: stomp.Connection | None = None


def _start_stomp(loop: asyncio.AbstractEventLoop) -> None:
    global _stomp_conn
    _stomp_conn = stomp.Connection(host_and_ports=[(_STOMP_HOST, _STOMP_PORT)])
    _stomp_conn.set_listener("", _PipelineListener(loop))
    _stomp_conn.connect(_STOMP_USER, _STOMP_PASS, wait=True,
                        headers={"client-id": "ui-server"})
    # Topics — broadcast, no competing consumption.
    _stomp_conn.subscribe(destination="/topic/loop.events",        id="ui-events",    ack="auto")
    _stomp_conn.subscribe(destination="/topic/tactical.decisions", id="ui-decisions", ack="auto")


@app.on_event("startup")
async def _on_startup() -> None:
    loop = asyncio.get_running_loop()
    await loop.run_in_executor(None, _start_stomp, loop)


