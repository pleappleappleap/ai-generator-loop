@app.post("/session/start")
async def session_start(req: SessionStartRequest) -> dict:
    """Create a new conversation and return its conversation_id."""
    resp = _coordinator_call({"op": "ConversationCreate", "name": req.name})
    return resp


@app.post("/workflow/new")
async def workflow_new(req: WorkflowNewRequest) -> dict:
    """Create a new workflow and its first run, returning workflow_id + run_id."""
    create_resp = _coordinator_call({
        "op":              "WorkflowCreate",
        "conversation_id": req.conversation_id,
        "name":            req.name,
        "workflow_path":   req.workflow_path,
        "description":     req.description,
        "budget_policy":   req.budget_policy,
        "max_retries":     req.max_retries,
        "max_inpaints":    req.max_inpaints,
    })
    if not create_resp.get("ok"):
        return create_resp

    workflow_id = create_resp["workflow_id"]

    # Create the first run immediately so the client has a run_id to use.
    resume_resp = _coordinator_call({"op": "WorkflowResume", "workflow_id": workflow_id})
    if not resume_resp.get("ok"):
        return resume_resp

    return {
        "ok":              True,
        "workflow_id":     workflow_id,
        "run_id":          resume_resp.get("run_id"),
        "conversation_id": req.conversation_id,
        "workflow_path":   req.workflow_path,
    }


@app.post("/workflow/{workflow_id}/resume")
async def workflow_resume(workflow_id: str, req: WorkflowResumeRequest) -> dict:
    """Resume a paused workflow, creating a new run."""
    payload: dict = {"op": "WorkflowResume", "workflow_id": workflow_id}
    if req.budget_policy is not None:
        payload["budget_policy"] = req.budget_policy
    if req.max_retries is not None:
        payload["max_retries"] = req.max_retries
    if req.max_inpaints is not None:
        payload["max_inpaints"] = req.max_inpaints
    resp = _coordinator_call(payload)
    return resp


@app.post("/workflow/{workflow_id}/start-run")
async def workflow_start_run(workflow_id: str, req: WorkflowStartRunRequest) -> dict:
    """Enqueue a generation request for a workflow's current run via STOMP."""
    image_uuid = str(_uuid_mod.uuid4())

    request_msg = {
        "image_uuid":       image_uuid,
        "session_uuid":     req.run_id,
        "sequence_number":  0,
        "workflow_path":    req.workflow_path,
        "workflow_id":      workflow_id,
        "conversation_id":  req.conversation_id,
        "prompt":           req.prompt,
        "workflow_params":  req.workflow_params or {},
    }

    if _stomp_conn and _stomp_conn.is_connected():
        _stomp_conn.send(
            destination="/queue/loop.request",
            body=json.dumps(request_msg),
            headers={"persistent": "true"},
        )
        return {"ok": True, "image_uuid": image_uuid}
    return {"ok": False, "error": "STOMP not connected"}


