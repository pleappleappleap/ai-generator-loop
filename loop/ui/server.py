"""UI backend server for the AI image generation pipeline.

FastAPI + WebSocket backend providing:

  REST endpoints
  ──────────────
  POST /session/start            — create a conversation
  POST /workflow/new             — create a workflow and first run within a conversation
  POST /workflow/{id}/resume     — resume a paused workflow (new run_id)
  POST /workflow/{id}/start-run  — enqueue a generation request for a workflow's current run
  POST /feedback                 — record thumbs up / down for an image
  GET  /history                  — list conversations, their workflows, and recent images
  GET  /image/{uuid}             — proxy ComfyUI image by UUID

  WebSocket endpoints
  ───────────────────
  WS /ws/gallery                 — push new image + decision events to the browser
  WS /ws/chat                    — bidirectional streaming chat with the tactical LLM

The server subscribes to two Artemis topics via STOMP:
  /topic/loop.events             — image generated by ComfyUI (captures image_path)
  /topic/tactical.decisions      — LLM decision per image (verdict + decision)

Image paths are cached in-process from loop.events messages and served via
/image/{uuid} by proxying to the ComfyUI URL.
"""

